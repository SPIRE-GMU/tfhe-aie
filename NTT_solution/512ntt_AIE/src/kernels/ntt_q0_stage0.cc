// ============================================================
// Modular add/sub
// ============================================================
static inline int32_t add_mod_q0(int32_t a, int32_t b)
{
    int32_t s = a + b;
    if (s >= static_cast<int32_t>(Q0)) s -= static_cast<int32_t>(Q0);
    return s;
}

static inline int32_t sub_mod_q0(int32_t a, int32_t b)
{
    int32_t d = a - b;
    if (d < 0) d += static_cast<int32_t>(Q0);
    return d;
}

// ============================================================
// Shoup modular multiplication
//
// Preconditions:
//   0 <= a < Q0
//   0 <= w < Q0
//   w_shoup = floor(w * 2^32 / Q0)
//
// Computes:
//   a * w mod Q0
//
// No %, no division in the runtime path.
// ============================================================
static inline int32_t mul_mod_q0_shoup(
    int32_t a,
    int32_t w,
    uint32_t w_shoup)
{
    const uint64_t au = static_cast<uint32_t>(a);
    const uint64_t wu = static_cast<uint32_t>(w);

    // Approximate quotient: floor(a * w_shoup / 2^32)
    const uint64_t qhat = (au * static_cast<uint64_t>(w_shoup)) >> 32;

    // Candidate remainder.
    uint64_t r = au * wu - qhat * static_cast<uint64_t>(Q0);

    // For this Shoup construction r is small; one correction is normally enough.
    // Keep two corrections for correctness-first implementation.
    if (r >= Q0) r -= Q0;
    if (r >= Q0) r -= Q0;

    return static_cast<int32_t>(r);
}

