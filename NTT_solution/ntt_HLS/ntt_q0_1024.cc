typedef ap_uint<64> pair64_t;

// Stage 0 is unchanged: no nontrivial twiddle.
static void stage0_stream(
    hls::stream<ap_int<32>>& in,
    hls::stream<ap_int<32>>& out)
{
#pragma HLS INLINE off
STAGE0_LOOP:
    for (int k = 0; k < NTT_N / 2; ++k) {
#pragma HLS PIPELINE II=1
        ap_uint<32> a = (ap_uint<32>)in.read();
        ap_uint<32> b = (ap_uint<32>)in.read();
        out.write((ap_int<32>)add_mod_q0(a,b));
        out.write((ap_int<32>)sub_mod_q0(a,b));
    }
}

// For one DIT stage, turn:
//   A[0..HALF-1], B[0..HALF-1]
// into (A[j],B[j]) pairs.
template<int LEN>
static void make_pairs(
    hls::stream<ap_int<32>>& in,
    hls::stream<pair64_t>& pairs)
{
#pragma HLS INLINE off
    constexpr int HALF   = LEN / 2;
    constexpr int GROUPS = NTT_N / LEN;

    ap_uint<32> a_buf[HALF];

GROUPS_LOOP:
    for (int g = 0; g < GROUPS; ++g) {
READ_A:
        for (int j = 0; j < HALF; ++j) {
#pragma HLS PIPELINE II=1
            a_buf[j] = (ap_uint<32>)in.read();
        }

READ_B_AND_PAIR:
        for (int j = 0; j < HALF; ++j) {
#pragma HLS PIPELINE II=1
            ap_uint<32> b = (ap_uint<32>)in.read();
            pair64_t p;
            p.range(31,0)  = a_buf[j];
            p.range(63,32) = b;
            pairs.write(p);
        }
    }
}

// One continuous N/2-butterfly loop per stage.
// For N=1024 this is exactly 512 butterflies per stage.
template<int LEN>
static void butterfly_engine(
    hls::stream<pair64_t>& pairs_in,
    hls::stream<pair64_t>& pairs_out,
    const ap_uint<32> W[LEN/2],
    const ap_uint<32> WS[LEN/2])
{
#pragma HLS INLINE off
    constexpr int HALF = LEN / 2;

BUTTERFLIES:
    for (int k = 0; k < NTT_N / 2; ++k) {
#pragma HLS PIPELINE II=1
        pair64_t p = pairs_in.read();

        ap_uint<32> u = p.range(31,0);
        ap_uint<32> x = p.range(63,32);

        // HALF is a power of two -> bit mask in hardware.
        const int j = k & (HALF - 1);

        ap_uint<32> v;
        if (j == 0) {
            v = x;
        } else {
            v = mul_mod_q0_shoup(x,W[j],WS[j]);
        }

        pair64_t q;
        q.range(31,0)  = add_mod_q0(u,v);
        q.range(63,32) = sub_mod_q0(u,v);
        pairs_out.write(q);
    }
}

// Convert pairs back to ordinary DIT stage order:
//   SUM[0..HALF-1], DIFF[0..HALF-1].
template<int LEN>
static void unpack_pairs(
    hls::stream<pair64_t>& pairs,
    hls::stream<ap_int<32>>& out)
{
#pragma HLS INLINE off
    constexpr int HALF   = LEN / 2;
    constexpr int GROUPS = NTT_N / LEN;

    ap_uint<32> diff_buf[HALF];

GROUPS_LOOP:
    for (int g = 0; g < GROUPS; ++g) {
READ_PAIR_AND_SUM_OUT:
        for (int j = 0; j < HALF; ++j) {
#pragma HLS PIPELINE II=1
            pair64_t p = pairs.read();
            out.write((ap_int<32>)p.range(31,0));
            diff_buf[j] = p.range(63,32);
        }

DIFF_OUT:
        for (int j = 0; j < HALF; ++j) {
#pragma HLS PIPELINE II=1
            out.write((ap_int<32>)diff_buf[j]);
        }
    }
}

