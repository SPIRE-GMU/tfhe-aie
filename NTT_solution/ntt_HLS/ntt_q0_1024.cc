// Input to this core is already:
//   signed input -> mod q0 -> negacyclic twist -> bit reversal
// Output is the complete 1024-point forward NTT result mod q0.
//
// Architecture: 10 concurrent radix-2 stages connected by streams.
// The pair-stream / continuous butterfly architecture is unchanged
// from the 512-point implementation.
// ============================================================

static ap_uint<32> add_mod_q0(ap_uint<32> a, ap_uint<32> b)
{
#pragma HLS INLINE
    ap_uint<33> s = (ap_uint<33>)a + (ap_uint<33>)b;
    if (s >= Q0) s -= Q0;
    return (ap_uint<32>)s;
}

static ap_uint<32> sub_mod_q0(ap_uint<32> a, ap_uint<32> b)
{
#pragma HLS INLINE
    return (a >= b) ? (ap_uint<32>)(a - b)
                    : (ap_uint<32>)((ap_uint<33>)a + Q0 - b);
}

static ap_uint<32> mul_mod_q0_shoup(
    ap_uint<32> a,
    ap_uint<32> w,
    ap_uint<32> w_shoup)
{
#pragma HLS INLINE
    ap_uint<64> p0 = a * w;
#pragma HLS BIND_OP variable=p0 op=mul impl=dsp
    ap_uint<64> p1 = a * w_shoup;
#pragma HLS BIND_OP variable=p1 op=mul impl=dsp
    ap_uint<32> qhat = p1.range(63,32);

    ap_uint<64> qprod = qhat * Q0;
#pragma HLS BIND_OP variable=qprod op=mul impl=dsp
    ap_uint<64> r = p0 - qprod;

    if (r >= Q0) r -= Q0;
    if (r >= Q0) r -= Q0;
    return (ap_uint<32>)r;
}

